from reportlab.lib.styles import getSampleStyleSheet
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
)
from datetime import datetime
import os


def generate_report(data):

    reports_folder = "reports"

    os.makedirs(reports_folder, exist_ok=True)

    filename = f"analysis_{datetime.now().strftime('%Y%m%d_%H%M%S')}.pdf"

    filepath = os.path.join(reports_folder, filename)

    doc = SimpleDocTemplate(filepath)

    styles = getSampleStyleSheet()

    elements = []

    # -------------------------------------------------
    # Title
    # -------------------------------------------------

    elements.append(
        Paragraph(
            "<b>NewsCredAI - AI News Analysis Report</b>",
            styles["Title"],
        )
    )

    elements.append(
        Paragraph(
            f"Generated On: {datetime.now().strftime('%d-%m-%Y %H:%M:%S')}",
            styles["Normal"],
        )
    )

    elements.append(Spacer(1, 15))

    # -------------------------------------------------
    # Scores
    # -------------------------------------------------

    credibility = data.get("credibility_score", 0)

    if credibility >= 75:
        verdict = "High Credibility"
    elif credibility >= 50:
        verdict = "Medium Credibility"
    else:
        verdict = "Low Credibility"

    elements.append(
        Paragraph(
            f"<b>Prediction:</b> {data.get('prediction')}",
            styles["Normal"],
        )
    )

    elements.append(
        Paragraph(
            f"<b>Confidence:</b> {data.get('confidence')}%",
            styles["Normal"],
        )
    )

    elements.append(
        Paragraph(
            f"<b>Credibility Score:</b> {credibility}%",
            styles["Normal"],
        )
    )

    elements.append(
        Paragraph(
            f"<b>Overall Verdict:</b> {verdict}",
            styles["Normal"],
        )
    )

    sentiment = data.get("sentiment", {})
    bias = data.get("bias", {})
    clickbait = data.get("clickbait", {})

    elements.append(
        Paragraph(
            f"<b>Sentiment:</b> {sentiment.get('label')}",
            styles["Normal"],
        )
    )

    elements.append(
        Paragraph(
            f"<b>Bias Score:</b> {bias.get('score')}%",
            styles["Normal"],
        )
    )

    elements.append(
        Paragraph(
            f"<b>Clickbait Score:</b> {clickbait.get('score')}%",
            styles["Normal"],
        )
    )

    elements.append(Spacer(1, 20))

    # -------------------------------------------------
    # Summary
    # -------------------------------------------------

    elements.append(
        Paragraph("<b>AI Summary</b>", styles["Heading2"])
    )

    summary = data.get("summary", {})

    elements.append(
        Paragraph(
            summary.get("text", "No summary available."),
            styles["BodyText"],
        )
    )

    elements.append(Spacer(1, 20))

    # -------------------------------------------------
    # Keywords
    # -------------------------------------------------

    elements.append(
        Paragraph("<b>Keywords</b>", styles["Heading2"])
    )

    keywords = data.get("keywords", {})

    words = []

    for item in keywords.get("top_keywords", []):

        if isinstance(item, list):
            words.append(item[0])

        elif isinstance(item, dict):
            words.append(item.get("word", ""))

        else:
            words.append(str(item))

    if words:
        elements.append(
            Paragraph(", ".join(words), styles["BodyText"])
        )
    else:
        elements.append(
            Paragraph("No keywords found.", styles["BodyText"])
        )

    elements.append(Spacer(1, 20))

    # -------------------------------------------------
    # Named Entities
    # -------------------------------------------------

    entities = data.get("entities", {})

    elements.append(
        Paragraph("<b>Named Entities</b>", styles["Heading2"])
    )

    elements.append(
        Paragraph(
            f"<b>Persons:</b> {', '.join(entities.get('persons', [])) or 'None'}",
            styles["BodyText"],
        )
    )

    elements.append(
        Paragraph(
            f"<b>Organizations:</b> {', '.join(entities.get('organizations', [])) or 'None'}",
            styles["BodyText"],
        )
    )

    elements.append(
        Paragraph(
            f"<b>Locations:</b> {', '.join(entities.get('locations', [])) or 'None'}",
            styles["BodyText"],
        )
    )

    elements.append(Spacer(1, 25))

    elements.append(
        Paragraph(
            "<i>Generated by NewsCredAI</i>",
            styles["Italic"],
        )
    )

    doc.build(elements)

    return filepath